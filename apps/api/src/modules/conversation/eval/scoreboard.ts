import { aggregate } from './aggregate';
import { compareToBaseline } from './baseline';
import {
  DIFFICULTIES,
  DIMENSIONS,
  type BaselineFile,
  type RunResults,
} from './eval-types';

/**
 * Renders `docs/evals/interview/scoreboard.md`: a pure projection of the
 * latest run plus the committed baseline (AC-6, AC-9). Regenerated on every
 * run; never hand edited.
 */
export function renderScoreboard(
  current: RunResults,
  baseline: BaselineFile | null,
): string {
  const agg = aggregate(current.cases);
  const comparison = compareToBaseline(current, baseline);
  const lines: string[] = [];

  lines.push('# Interview simulator eval scoreboard');
  lines.push('');
  lines.push(
    '_Generated by `npm run eval:interview` (spec 0011). Do not hand edit; this file is a projection of the latest results file and `baseline.json`._',
  );
  lines.push('');
  lines.push('## Latest run');
  lines.push('');
  lines.push(`- Date: ${current.meta.date}`);
  lines.push(
    `- Commit: ${current.meta.gitCommit}${current.meta.gitDirty ? ' (dirty)' : ''}`,
  );
  lines.push(
    `- Generator: ${current.meta.provider} / ${current.meta.generatorModel} · Judge: ${current.meta.judgeModel}`,
  );
  lines.push(`- Cases: ${current.meta.caseCount}`);
  lines.push(`- Dataset hash: \`${current.meta.datasetHash.slice(0, 12)}…\``);
  lines.push(
    `- Estimated cost: ${
      current.meta.estimatedCostUsd === null
        ? 'n/a (model missing from the price table)'
        : `$${current.meta.estimatedCostUsd.toFixed(4)}`
    } · Tokens: ${current.meta.tokenTotals.inputTokens} in / ${current.meta.tokenTotals.outputTokens} out`,
  );
  if (current.meta.aborted) {
    lines.push('- **Run aborted by --max-cost; results are partial.**');
  }
  lines.push('');

  lines.push('## Scores by dimension');
  lines.push('');
  lines.push('| Dimension | Mean | Scored cases | Judge errors | Δ vs baseline | Noise band | Significance |');
  lines.push('|---|---|---|---|---|---|---|');
  for (const dimension of DIMENSIONS) {
    const d = agg.perDimension[dimension];
    const delta = comparison.perDimension[dimension];
    const band = baseline?.noiseBand?.[dimension];
    lines.push(
      `| ${dimension} | ${formatMean(d.mean)} | ${d.scoredCases} | ${d.judgeErrors} | ${formatDelta(
        delta.delta,
        comparison,
      )} | ${band === undefined ? '—' : `±${band.toFixed(2)}`} | ${formatSignificance(delta.significant, delta.delta)} |`,
    );
  }
  lines.push('');

  if (!comparison.hasBaseline) {
    lines.push('_No committed baseline yet; deltas unavailable._');
    lines.push('');
  } else if (!comparison.comparable) {
    lines.push(
      '_Baseline delta **not comparable**: the dataset hash differs from the baseline run. Re-establish the baseline on the current dataset._',
    );
    lines.push('');
  }

  lines.push('## Scores by difficulty');
  lines.push('');
  lines.push(`| Difficulty | ${DIMENSIONS.join(' | ')} | Cases |`);
  lines.push(`|---|${DIMENSIONS.map(() => '---').join('|')}|---|`);
  for (const difficulty of DIFFICULTIES) {
    const row = agg.perDifficulty[difficulty];
    const caseCount = current.cases.filter(
      (c) => c.difficulty === difficulty,
    ).length;
    if (caseCount === 0) continue;
    lines.push(
      `| ${difficulty} | ${DIMENSIONS.map((dim) => formatMean(row[dim].mean)).join(' | ')} | ${caseCount} |`,
    );
  }
  lines.push('');

  const erroredLines: string[] = [];
  for (const caseId of agg.generationErrors) {
    erroredLines.push(`- \`${caseId}\`: generation_error (turn pair failed after one retry)`);
  }
  for (const [caseId, dims] of Object.entries(agg.judgeErrorCases)) {
    erroredLines.push(`- \`${caseId}\`: judge_error on ${dims.join(', ')}`);
  }
  if (erroredLines.length > 0) {
    lines.push('## Errored cases');
    lines.push('');
    lines.push(...erroredLines);
    lines.push('');
  }

  const guardFirings = current.cases.filter((c) => c.guardFired);
  if (guardFirings.length > 0) {
    lines.push('## Ownership guard firings');
    lines.push('');
    for (const c of guardFirings) {
      lines.push(
        `- \`${c.caseId}\`: ${c.honestyLayers?.guard.reason ?? 'guard fired'}`,
      );
    }
    lines.push('');
  }

  return `${lines.join('\n')}\n`;
}

function formatMean(mean: number | null): string {
  return mean === null ? '—' : mean.toFixed(2);
}

function formatDelta(
  delta: number | null,
  comparison: { hasBaseline: boolean; comparable: boolean },
): string {
  if (!comparison.hasBaseline) return '—';
  if (!comparison.comparable) return 'not comparable';
  if (delta === null) return '—';
  const sign = delta > 0 ? '+' : '';
  return `${sign}${delta.toFixed(2)}`;
}

function formatSignificance(
  significant: boolean | null,
  delta: number | null,
): string {
  if (significant === null || delta === null) return '—';
  return significant ? '**significant**' : 'not significant';
}
